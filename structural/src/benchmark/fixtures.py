"""Frozen, outcome-independent input generation for the benchmark."""
from pathlib import Path
import hashlib,json,random

SEED=4622026
DIMENSIONS=(2,4,6,8,10,12)
METHODS=('pair','antichain','exterior')
CAP_SECONDS=10
MEMORY_BYTES=1073741824
REPETITIONS=3
WARMUPS=1

def encode(value):
    return json.dumps(value,indent=2,sort_keys=True,allow_nan=False)+'\n'

def instances():
    items=[]
    def add(name,family,data,**metadata):
        items.append({'name':name,'family':family,'structure':data,'metadata':metadata})
    for n in DIMENSIONS:
        for mode in ('separate','joint'):
            data={'n':n,'U':2,'pa':[[[] if i==0 else [i-1] for i in range(n)] for _ in range(2)],
                  'fac':[[[n-2],[n-1]] if mode=='separate' else [[n-2,n-1]] for _ in range(2)]}
            add(f'chain_{n:02}_{mode}','matched_chain',data,fitness=mode,
                expected_horizons={'full':n,'growth':n} if mode=='separate' else {'full':'infinite','growth':'infinite'})
    pa=[[[2],[3],[1,3],[]],[[2],[3],[1],[]]]
    for mode,fac,h in [('selected',[[[],[]],[[0],[]]],{'full':6,'growth':6}),
                       ('selection_free',[[],[]],{'full':4,'growth':0})]:
        add('delay_04_'+mode,'selection_delay',{'n':4,'U':2,'pa':pa,'fac':fac},expected_horizons=h)
    # Each graph is generated before any horizon classification. No rejection,
    # outcome-based screening, sorting, or substitution is performed.
    rng=random.Random(SEED)
    for n in (4,6,8):
        for actions,arity in ((2,1),(3,2),(3,3)):
            pa=[];fac=[]
            for u in range(actions):
                rows=[]
                for i in range(n):
                    selected=[j for j in range(i) if rng.random()<0.35]
                    if len(selected)>2:selected=sorted(rng.sample(selected,2))
                    rows.append(selected)
                # Structural branching is guaranteed without inspecting answers.
                rows[2]=[0,1]
                pa.append(rows)
                first=sorted([n-1,*rng.sample(range(n-1),arity-1)])
                second=sorted(rng.sample(range(n),arity))
                fac.append([first,second])
            add(f'dag_{n:02}_u{actions}_a{arity}','branching_dag',
                {'n':n,'U':actions,'pa':pa,'fac':fac},seed=SEED,scope_arity=arity,
                generation='parent j<i with Bernoulli .35, at most2; node2 parents0,1; two scopes per action; no screening')
    for n in (2,4,8,12):
        add(f'refresh_{n:02}','refresh',{'n':n,'U':n,
          'pa':[[[] if i==a else [i] for i in range(n)] for a in range(n)],
          'fac':[[[i] for i in range(n)] for _ in range(n)]},
          expected_horizons={'full':'infinite','growth':'infinite'},expected_unpruned_states=2**n)
    add('zero_coordinates','zero',{'n':0,'U':2,'pa':[[],[]],'fac':[[[]],[]]},
        expected_horizons={'full':0,'growth':0})
    add('cycle_outside_ancestry','partial_precheck',{'n':3,'U':2,
        'pa':[[[],[0],[2]],[[],[0],[2]]],'fac':[[[1]],[[1]]]},
        expected_horizons={'full':'infinite','growth':2})
    if len(items)!=29 or len({x['name'] for x in items})!=29:raise RuntimeError('Input inventory')
    return items

